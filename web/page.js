  function run() {
    var text = $("#txt").value.trim();
    if (!text) { $("#res").innerHTML = "<div class='res'><p>Paste or load a complaint first.</p></div>"; return; }
    py.globals.set("_text", text);
    py.globals.set("_th", +$("#th").value);
    var o = JSON.parse(py.runPython("driver.classify(_text, _th)"));
    var head = o.routed
      ? "<span class='pill ok'>routed</span> <span class='big'>" + esc(o.queue) + "</span><p style='margin-top:6px'>Product: <b>" + esc(o.product) + "</b> at " + pct(o.confidence, 0) + " confidence.</p>"
      : "<span class='pill warn'>handed to a person</span> <span class='big'>" + esc(o.queue) + "</span><p style='margin-top:6px'>Best guess: " + esc(o.product) + ", but " + esc(o.reason) + ".</p>";
    var bars = o.ranking.map(function (x) {
      return "<div class='b'><span class='l'>" + esc(short(x.product)) + "</span><span class='t'><i style='width:" + Math.round(100 * x.p) + "%'></i></span><span class='p'>" + pct(x.p, 0) + "</span></div>";
    }).join("");
    var words = o.evidence.length ? "<div class='chips'>" + o.evidence.map(function (w) { return "<span class='chip'>" + esc(w) + "</span>"; }).join("") + "</div>" : "<p>None it recognises.</p>";
    var sim = o.similar.map(function (s) {
      return "<div class='case'><b>" + esc(short(s.product)) + "</b> · " + esc(s.issue) + " <span class='dimc'>(" + esc(s.company_response) + ")</span><div class='q'>“" + esc(s.excerpt) + "…”</div></div>";
    }).join("") || "<p>No similar complaints found.</p>";
    var ex = info.examples.filter(function (e) { return e.text.trim() === text; })[0];
    if (ex) {
      var right = ex.product === o.product;
      head += "<p style='margin-top:6px'>The consumer filed this under <b>" + esc(ex.product) + "</b> (issue: " + esc(ex.issue) + "). " +
        (right ? "<span class='pill ok'>right product</span>" : "<span class='pill bad'>wrong product</span>") +
        (o.routed ? "" : " It wasn't routed, so a person would have caught it either way.") + "</p>";
    }
    $("#res").innerHTML = "<div class='res'>" + head +
      "<h3 style='margin-top:14px'>How sure it was, by product</h3><div class='bars'>" + bars + "</div>" +
      "<h3 style='margin-top:14px'>Words that pushed it there</h3>" + words +
      "<h3 style='margin-top:14px'>Similar past complaints, for whoever picks it up</h3>" + sim + "</div>";
  }

