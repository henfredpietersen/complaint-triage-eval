  function topPair(r) {
    // The two products confused with each other most often, counted both ways.
    var best = null;
    r.labels.forEach(function (a, i) {
      r.labels.slice(i + 1).forEach(function (b) {
        var n = r.confusion[a][b] + r.confusion[b][a];
        if (!best || n > best.n) best = { a: a, b: b, n: n };
      });
    });
    return best ? best.n + " complaints were swapped between " + esc(short(best.a)) + " and " + esc(short(best.b)) + "." : "";
  }

